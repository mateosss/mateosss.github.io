"""Pandoc filter: replace {{NAME}} in text, links and raw blocks with semester variables.

Variables come from res/semester.yaml (generated by org/generate.py from
org/variables.jsonc). {{DATE}} is the date of the deck being built, which is
given with --metadata=deck:<key> (e.g. l1). The same date is set as the
document `date`, so it shows in the footer of every slide.
"""

import re
import sys

import panflute as pf

# Pandoc percent-encodes braces in link targets, so accept {{NAME}} and %7B%7BNAME%7D%7D
VAR_RE = re.compile(r"(?:\{\{|%7B%7B)\s*([A-Za-z0-9_]+)\s*(?:\}\}|%7D%7D)", re.IGNORECASE)


def prepare(doc):
    doc.semester_vars = {k: str(v) for k, v in doc.get_metadata("vars", {}).items()}
    dates = doc.get_metadata("dates", {})
    deck = doc.get_metadata("deck")
    if deck not in dates:
        sys.exit(f"vars.py: no date for deck '{deck}' in res/semester.yaml")
    doc.semester_vars["DATE"] = str(dates[deck])
    doc.metadata["date"] = pf.MetaString(doc.semester_vars["DATE"])


def replace(text, doc):
    def sub(m):
        if m.group(1) not in doc.semester_vars:
            sys.exit(f"vars.py: undefined variable {m.group(1)}")
        return doc.semester_vars[m.group(1)]

    return VAR_RE.sub(sub, text)


def action(elem, doc):
    if isinstance(elem, pf.Str):
        elem.text = replace(elem.text, doc)
    elif isinstance(elem, (pf.Link, pf.Image)):
        elem.url = replace(elem.url, doc)
    elif isinstance(elem, (pf.RawBlock, pf.RawInline)):
        elem.text = replace(elem.text, doc)


def main(doc=None):
    return pf.run_filter(action, prepare=prepare, doc=doc)


if __name__ == "__main__":
    main()
